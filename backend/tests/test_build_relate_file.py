"""The Relate (.rl) release builder: what it reads from the script, and what
makes it refuse.

From the ticket "Check out relate from Neo4J" (step 5, 24 Nov 2026).
``relate-db`` and ``bods-neo4j`` are not backend dependencies, so these pin
the pure parts; the full build is run by ``publish-relate-file.yml``.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "build_relate_file.py"
_spec = importlib.util.spec_from_file_location("_build_relate_file", _SCRIPT)
assert _spec and _spec.loader
brf = importlib.util.module_from_spec(_spec)
sys.modules["_build_relate_file"] = brf
_spec.loader.exec_module(brf)

_SCRIPT_TEXT = """\
// BODS graph — portable Cypher import, generated by bods-neo4j to-cypher.
// :Entity (2)
UNWIND [
  {k: 'e1', p: {name: 'A; B'}},
  {k: 'e2', p: {name: 'O\\'Brien\\nLtd'}}
] AS row
MERGE (n:Entity {recordId: row.k}) SET n += row.p;
// :Person (1)
UNWIND [{k: 'p1', p: {}}] AS row MERGE (n:Person {recordId: row.k}) SET n += row.p;
// (Person)-[:OWNS]->(Entity) (1,234)
UNWIND [{s: 'p1', t: 'e1', p: {}}] AS row
MATCH (a:Person {recordId: row.s}) MATCH (b:Entity {recordId: row.t})
CREATE (a)-[r:OWNS]->(b) SET r += row.p;
// Summary
MATCH (n) RETURN count(n);
"""


@pytest.fixture
def script(tmp_path: Path) -> Path:
    p = tmp_path / "graph.cypher"
    p.write_text(_SCRIPT_TEXT, encoding="utf-8")
    return p


def test_statements_end_at_a_line_ending_semicolon(script: Path) -> None:
    got = list(brf.statements(script))
    assert len(got) == 4
    # A ';' inside a literal does not end a statement.
    assert "'A; B'" in got[0]
    assert not any(s.endswith(";") for s in got)
    assert not any(line.startswith("//") for s in got for line in s.splitlines())


def test_a_script_cut_inside_a_statement_is_refused(tmp_path: Path) -> None:
    p = tmp_path / "cut.cypher"
    p.write_text("UNWIND [1] AS x\nRETURN x;\nUNWIND [2] AS y\n", encoding="utf-8")
    with pytest.raises(ValueError):
        list(brf.statements(p))


def test_the_announced_counts_are_read_from_the_header(script: Path) -> None:
    nodes, edges = brf.announced_counts(script)
    assert nodes == {"Entity": 2, "Person": 1}
    assert edges == {("Person", "OWNS", "Entity"): 1234}


def test_matching_counts_raise_nothing() -> None:
    nodes = {"Entity": 2, "Person": 1}
    edges = {("Person", "OWNS", "Entity"): 3}
    # An entity subtype label the header does not count is ignored.
    assert brf.count_mismatches(nodes, {**nodes, "registeredEntity": 2}, edges, edges) == []


def test_any_differing_count_is_named() -> None:
    problems = brf.count_mismatches(
        {"Entity": 2}, {"Entity": 1},
        {("Person", "OWNS", "Entity"): 3},
        {("Person", "OWNS", "Entity"): 2, ("Person", "CONTROLS", "Entity"): 1},
    )
    assert problems == [
        ":Entity announced 2, loaded 1",
        "(Person)-[:CONTROLS]->(Entity) announced 0, loaded 1",
        "(Person)-[:OWNS]->(Entity) announced 3, loaded 2",
    ]


def test_an_edge_endpoint_is_counted_under_its_base_label() -> None:
    base = {"Entity": 1, "Person": 1}
    assert brf._base(["registeredEntity", "Entity"], base) == "Entity"
    assert brf._base(["Person"], base) == "Person"


def test_the_builder_sets_do_not_track_before_relate_is_imported() -> None:
    text = _SCRIPT.read_text(encoding="utf-8")
    assert text.index('os.environ["DO_NOT_TRACK"] = "1"') < text.index("import relate")
